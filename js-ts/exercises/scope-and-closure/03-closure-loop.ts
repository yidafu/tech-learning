/**
 * 大纲章节：阶段 1.2 作用域与闭包
 * 主题：经典循环闭包问题 —— var 共享一个绑定的三层原因、let 的 CreatePerIterationEnvironment 修复、IIFE 与 setTimeout 第三参数的手动修复
 * 运行：npx tsx exercises/scope-and-closure/03-closure-loop.ts
 * 预期输出：
 * [0] var：循环结束后才调用回调 = 3, 3, 3
 * [0] let：循环结束后才调用回调 = 0, 1, 2
 * [1] 同步循环结束，i = 3（这行先于所有回调打印）
 * [*] 以下全部是异步回调的输出（按定时器注册顺序执行）
 * [1] var + setTimeout：i = 3
 * [1] var + setTimeout：i = 3
 * [1] var + setTimeout：i = 3
 * [2] let + setTimeout：j = 0
 * [2] let + setTimeout：j = 1
 * [2] let + setTimeout：j = 2
 * [3] IIFE 修复：captured = 0
 * [3] IIFE 修复：captured = 1
 * [3] IIFE 修复：captured = 2
 * [4] setTimeout 第三参数：v = 0
 * [4] setTimeout 第三参数：v = 1
 * [4] setTimeout 第三参数：v = 2
 */

// =============================================================================
// 读法提示（闭卷复述清单）：
// 1. 同步层：for 循环瞬间跑完，退出时 i === 3（条件失败时的值）
// 2. 队列层：setTimeout 的回调进入定时器队列，同步代码全部执行完才轮到它们
// 3. 绑定层（本质）：var 的 i 是"整个函数/模块作用域唯一绑定"，
//    三个回调的 [[Environment]] 指向同一个环境记录 → 解析 i 得到同一个格子 → 都读到 3
// let 的修复是规范级机制：ECMA-262 §14.7.4.4 CreatePerIterationEnvironment，
// 每轮迭代新建环境记录、把上一轮的值"复制"进来、增量表达式也在新环境里执行。
// =============================================================================

// -----------------------------------------------------------------------------
// [0] 同步预演：不用定时器就能看到本质 —— 回调保存的是"未来才执行的读取"
// -----------------------------------------------------------------------------
const varReaders: Array<() => number> = [];
for (var s = 0; s < 3; s++) {
  varReaders.push((): number => s); // 三个函数的 [[Environment]] 指向同一个环境，共享 s 绑定
}
// 循环已结束、s 已是 3，此刻才调用回调 → 全部读到同一个绑定的终值
console.log(`[0] var：循环结束后才调用回调 = ${varReaders.map((f: () => number): number => f()).join(", ")}`);

const letReaders: Array<() => number> = [];
for (let t = 0; t < 3; t++) {
  letReaders.push((): number => t); // 每轮迭代一个新环境（CreatePerIterationEnvironment），t 是每轮的新绑定
}
console.log(`[0] let：循环结束后才调用回调 = ${letReaders.map((f: () => number): number => f()).join(", ")}`);

// -----------------------------------------------------------------------------
// [1] var + setTimeout：打印三个 3 的完整现场
// -----------------------------------------------------------------------------
for (var i = 0; i < 3; i++) {
  // 注册回调：此刻不执行，只是把函数对象交给定时器队列
  setTimeout((): void => console.log(`[1] var + setTimeout：i = ${i}`));
}
console.log("[1] 同步循环结束，i = 3（这行先于所有回调打印）"); // 同步代码先于所有回调

// -----------------------------------------------------------------------------
// [2] let + setTimeout：每轮迭代一个新环境，回调各自闭包自己的 j
// -----------------------------------------------------------------------------
for (let j = 0; j < 3; j++) {
  setTimeout((): void => console.log(`[2] let + setTimeout：j = ${j}`));
}

// -----------------------------------------------------------------------------
// [3] IIFE 修复（var 时代）：在"回调创建时"立即调用函数产生新环境，
// 当轮的 k 作为实参传入 —— 参数是每次调用的全新绑定
// -----------------------------------------------------------------------------
for (var k = 0; k < 3; k++) {
  ((captured: number): void => {
    // captured 是这一次函数调用的新绑定，值是"注册时刻"的 k（同步循环内，值正确）
    setTimeout((): void => console.log(`[3] IIFE 修复：captured = ${captured}`));
  })(k);
}

// -----------------------------------------------------------------------------
// [4] setTimeout 第三参数：setTimeout(fn, delay, ...args) —— 注册时保存 args，
// 定时器触发时用保存的值调用回调；参数即新绑定，机制上与 IIFE 等价
// -----------------------------------------------------------------------------
for (var m = 0; m < 3; m++) {
  setTimeout((v: number): void => console.log(`[4] setTimeout 第三参数：v = ${v}`), 0, m);
}

console.log("[*] 以下全部是异步回调的输出（按定时器注册顺序执行）");
// 上面所有 setTimeout 延迟都是 0（未传 delay 默认 0），同延迟定时器按注册顺序触发，
// 所以输出顺序 = 四段代码的注册顺序 —— 结果是确定性的
