#!/usr/bin/env node
/**
 * 生成 static/ts/ 下的浏览器内 TypeScript 编译器资源：
 * 1. typescript.js  — node_modules/typescript/lib/typescript.js（UMD，暴露 window.ts）
 * 2. ts-libs.js     — 全部 lib*.d.ts 内容内嵌为 window.__TS_LIB_FILES__（键名 /libs/<file>）
 *
 * 用法：node scripts/gen-ts-libs.mjs
 * 仅在工作区本地使用；产物体积大（~20 MB），不提交也不部署。
 */
import {createWriteStream} from 'node:fs';
import {copyFile, mkdir, readdir, readFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const siteDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tsLibDir = path.join(siteDir, 'node_modules', 'typescript', 'lib');
const outDir = path.join(siteDir, 'static', 'ts');

await mkdir(outDir, {recursive: true});

// 1) 编译器本体（UMD）
await copyFile(path.join(tsLibDir, 'typescript.js'), path.join(outDir, 'typescript.js'));

// 2) lib*.d.ts 全量内嵌（es5–es2022 / dom / decorators / esnext 全链，
//    供 createProgram 的虚拟文件系统解析；skipLibCheck 保证检查性能）
const libFiles = (await readdir(tsLibDir)).filter((f) => /^lib\..+\.d\.ts$/.test(f));
if (libFiles.length === 0) {
  throw new Error(`在 ${tsLibDir} 未找到 lib*.d.ts，请确认 typescript 已安装`);
}

const out = createWriteStream(path.join(outDir, 'ts-libs.js'));
out.write(
  '// Generated by scripts/gen-ts-libs.mjs — do not edit.\n' +
    'window.__TS_LIB_FILES__ = {\n',
);
let total = 0;
for (const file of libFiles) {
  const content = await readFile(path.join(tsLibDir, file), 'utf8');
  total += content.length;
  out.write(`  ${JSON.stringify(`/libs/${file}`)}: ${JSON.stringify(content)},\n`);
}
out.end('};\n');

console.log(`✔ static/ts/typescript.js`);
console.log(`✔ static/ts/ts-libs.js (${libFiles.length} 个 lib 声明文件, ${(total / 1024 / 1024).toFixed(1)} MB)`);
